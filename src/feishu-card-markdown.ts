/** 飞书 markdown 特殊字符 → HTML 实体映射（官方文档完整清单）。 */
const CARD_MD_ENTITY: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '*': '&#42;',
  '~': '&#126;',
  _: '&#95;',
  '`': '&#96;',
  '[': '&#91;',
  ']': '&#93;',
  '(': '&#40;',
  ')': '&#41;',
  '#': '&#35;',
  '-': '&#45;',
  '!': '&#33;',
  '/': '&#47;',
  '\\': '&#92;',
  ':': '&#58;',
  '+': '&#43;',
  '"': '&#34;',
  "'": '&#39;',
  $: '&#36;',
  '.': '&#46;',
  '|': '&#124;',
};

/** 把动态文本转成飞书 markdown 中不会被解释的纯文本。 */
export function escapeCardMarkdownText(text: string): string {
  return text.replace(
    /[&<>*~_`[\]()#!/\\:+"'$.|-]/gu,
    (ch) => CARD_MD_ENTITY[ch] ?? ch,
  );
}
